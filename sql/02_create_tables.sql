-- 02_create_tables.sql
SET search_path TO hospital, public;

-- Re-runnable development setup.
DROP TABLE IF EXISTS payments, bills, lab_results, lab_tests, prescription_items,
    prescriptions, medicines, admissions, rooms, appointments, insurance,
    doctors, patients, departments CASCADE;

CREATE TABLE departments (
    department_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_name VARCHAR(100) NOT NULL UNIQUE,
    location VARCHAR(100) NOT NULL,
    phone_extension VARCHAR(10),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE patients (
    patient_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(60) NOT NULL,
    last_name VARCHAR(60) NOT NULL,
    date_of_birth DATE NOT NULL,
    gender VARCHAR(20) NOT NULL,
    phone VARCHAR(20) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    city VARCHAR(80) NOT NULL,
    blood_group VARCHAR(5),
    emergency_contact_name VARCHAR(120),
    emergency_contact_phone VARCHAR(20),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE doctors (
    doctor_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id BIGINT NOT NULL REFERENCES departments(department_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    first_name VARCHAR(60) NOT NULL,
    last_name VARCHAR(60) NOT NULL,
    specialization VARCHAR(100) NOT NULL,
    license_number VARCHAR(40) NOT NULL UNIQUE,
    experience_years INTEGER NOT NULL,
    consultation_fee NUMERIC(10,2) NOT NULL,
    phone VARCHAR(20) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE appointments (
    appointment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL REFERENCES patients(patient_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    doctor_id BIGINT NOT NULL REFERENCES doctors(doctor_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    appointment_date TIMESTAMP NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'Scheduled',
    reason TEXT,
    notes TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE rooms (
    room_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_number VARCHAR(20) NOT NULL UNIQUE,
    room_type VARCHAR(30) NOT NULL,
    floor_number INTEGER NOT NULL,
    daily_rate NUMERIC(10,2) NOT NULL,
    is_available BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE admissions (
    admission_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL REFERENCES patients(patient_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    room_id BIGINT REFERENCES rooms(room_id)
        ON UPDATE CASCADE ON DELETE SET NULL,
    attending_doctor_id BIGINT NOT NULL REFERENCES doctors(doctor_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    admission_date DATE NOT NULL,
    discharge_date DATE,
    admission_reason TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'Admitted',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE medicines (
    medicine_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medicine_name VARCHAR(120) NOT NULL UNIQUE,
    category VARCHAR(80) NOT NULL,
    unit_price NUMERIC(10,2) NOT NULL,
    stock_quantity INTEGER NOT NULL DEFAULT 0,
    reorder_level INTEGER NOT NULL DEFAULT 10,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE prescriptions (
    prescription_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL REFERENCES patients(patient_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    doctor_id BIGINT NOT NULL REFERENCES doctors(doctor_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    prescription_date DATE NOT NULL DEFAULT CURRENT_DATE,
    diagnosis VARCHAR(200),
    notes TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE prescription_items (
    prescription_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prescription_id BIGINT NOT NULL REFERENCES prescriptions(prescription_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    medicine_id BIGINT NOT NULL REFERENCES medicines(medicine_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    dosage VARCHAR(100) NOT NULL,
    frequency VARCHAR(100) NOT NULL,
    duration_days INTEGER NOT NULL,
    quantity INTEGER NOT NULL,
    unit_price NUMERIC(10,2) NOT NULL
);

CREATE TABLE lab_tests (
    lab_test_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    test_name VARCHAR(120) NOT NULL UNIQUE,
    category VARCHAR(80) NOT NULL,
    standard_price NUMERIC(10,2) NOT NULL,
    turnaround_hours INTEGER NOT NULL
);

CREATE TABLE lab_results (
    lab_result_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL REFERENCES patients(patient_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    doctor_id BIGINT REFERENCES doctors(doctor_id)
        ON UPDATE CASCADE ON DELETE SET NULL,
    lab_test_id BIGINT NOT NULL REFERENCES lab_tests(lab_test_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    ordered_at TIMESTAMP NOT NULL,
    result_date TIMESTAMP,
    result_value VARCHAR(200),
    unit VARCHAR(40),
    reference_range VARCHAR(100),
    result_status VARCHAR(20) NOT NULL DEFAULT 'Pending',
    notes TEXT
);

CREATE TABLE insurance (
    insurance_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL REFERENCES patients(patient_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    provider_name VARCHAR(120) NOT NULL,
    policy_number VARCHAR(60) NOT NULL UNIQUE,
    plan_name VARCHAR(100) NOT NULL,
    coverage_percent NUMERIC(5,2) NOT NULL,
    coverage_limit NUMERIC(12,2) NOT NULL,
    valid_from DATE NOT NULL,
    valid_until DATE NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE bills (
    bill_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL REFERENCES patients(patient_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    doctor_id BIGINT REFERENCES doctors(doctor_id)
        ON UPDATE CASCADE ON DELETE SET NULL,
    admission_id BIGINT REFERENCES admissions(admission_id)
        ON UPDATE CASCADE ON DELETE SET NULL,
    bill_date DATE NOT NULL DEFAULT CURRENT_DATE,
    subtotal NUMERIC(12,2) NOT NULL,
    discount_amount NUMERIC(12,2) NOT NULL DEFAULT 0,
    insurance_covered_amount NUMERIC(12,2) NOT NULL DEFAULT 0,
    tax_amount NUMERIC(12,2) NOT NULL DEFAULT 0,
    total_amount NUMERIC(12,2) NOT NULL,
    paid_amount NUMERIC(12,2) NOT NULL DEFAULT 0,
    status VARCHAR(20) NOT NULL DEFAULT 'Unpaid',
    description TEXT,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE payments (
    payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bill_id BIGINT NOT NULL REFERENCES bills(bill_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    payment_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    amount NUMERIC(12,2) NOT NULL,
    payment_method VARCHAR(30) NOT NULL,
    transaction_reference VARCHAR(80) NOT NULL UNIQUE,
    status VARCHAR(20) NOT NULL DEFAULT 'Completed'
);
